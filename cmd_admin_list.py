import telebot

COMMANDS = ["إدارة", "ادارة", "شؤون الإدارة", "شؤون الادارة"]

def handle(bot, message):
    if message.text not in COMMANDS:
        return

    user_name = message.from_user.first_name
    user_id = message.from_user.id

    DEVELOPER_ID = 5860391324

    if user_id != DEVELOPER_ID:
        # رسائل عشوائية مضحكة
        funny_msgs = [
            f"😂 أيُّهَا العَبْد! {user_name}، البوابة مغلقة عنك… حاول مرة ثانية وستُطرد من الإمبراطورية!",
            f"🌚 {user_name}، ما تحاول تفتح شؤون الإدارة… أو ستصبح مشعوذًا بدون عصاك!",
            f"😏 {user_name}، التسلل للإدارة ممنوع! ارجع واجلس مكانك المهيب!",
            f"😔 أيها الغبي {user_name}، لا تتجرأ على الإدارة… هذا محظور على البشر العاديين!",
            f"🤣 {user_name}، ضحكتنا عليك! الإدارة ليست مكانك، ابتعد قبل أن يُكتشف سرك!"
        ]
        import random
        bot.reply_to(message, random.choice(funny_msgs))
        return

    # الرسالة الرسمية للمطور
    admin_text = f"""
╔═════════════════╗
       إدارة البوت 
╚═════════════════╝

مرحباً بك يا {user_name} 👑
━━━━━━━━━━━━━━━

⌔︙قائمة شؤون الإدارة:
—————————————
• إدارة المستخدمين » إضافة / حذف / تعديل المستخدمين
• حظر المستخدم » منع أي مستخدم من استخدام البوت
• اشعار » أرسال رسائل للمستخدمين
• شحن الذهب » إضافة ذهب لأي مستخدم
• إدارة الألعاب » تفعيل / تعطيل الألعاب
• إدارة المتجر » تعديل المنتجات والجوائز
• رست » رست البوت
• الإحصائيات » مشاهدة جميع رصيد اللاعبين ومستوى النشاط
• رسائل المطور » إرسال إشعارات مباشرة لجميع المستخدمين
• ايقاف / تشغيل »  ايقاف وتشغيل البوت 
—————————————
"""
    bot.reply_to(message, admin_text)

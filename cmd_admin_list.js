const DEV_IDS = process.env.DEV_IDS ? process.env.DEV_IDS.split(',').map(id => id.trim()) : [];

const COMMANDS = ["إدارة", "ادارة", "شؤون الإدارة", "شؤون الادارة"];

function handle(bot, ctx) {
    const text = ctx.message.text.trim();
    const user_name = ctx.from.first_name;
    const user_id = ctx.from.id;

    if (!COMMANDS.includes(text)) return;

    if (!DEV_IDS.includes(user_id.toString())) {
        // رسائل عشوائية مضحكة
        const funny_msgs = [
            `😂 أيُّهَا العَبْد! ${user_name}، البوابة مغلقة عنك… حاول مرة ثانية وستُطرد من الإمبراطورية!`,
            `🌚 ${user_name}، ما تحاول تفتح شؤون الإدارة… أو ستصبح مشعوذًا بدون عصاك!`,
            `😏 ${user_name}، التسلل للإدارة ممنوع! ارجع واجلس مكانك المهيب!`,
            `😔 أيها الغبي ${user_name}، لا تتجرأ على الإدارة… هذا محظور على البشر العاديين!`,
            `🤣 ${user_name}، ضحكتنا عليك! الإدارة ليست مكانك، ابتعد قبل أن يُكتشف سرك!`
        ];
        const msg = funny_msgs[Math.floor(Math.random() * funny_msgs.length)];
        ctx.reply(msg);
        return;
    }

    // الرسالة الرسمية للمطور
    const admin_text = `
╔═════════════════╗
       إدارة البوت 
╚═════════════════╝

مرحباً بك يا ${user_name} 👑
━━━━━━━━━━━━━━━

⌔︙قائمة شؤون الإدارة:
—————————————
• إدارة المستخدمين » إضافة / حذف / تعديل المستخدمين
• حظر المستخدم » منع أي مستخدم من استخدام البوت
• اشعار » إرسال رسائل للمستخدمين
• شحن الذهب » إضافة ذهب لأي مستخدم
• إدارة الألعاب » تفعيل / تعطيل الألعاب
• إدارة المتجر » تعديل المنتجات والجوائز
• رست » رست البوت
• الإحصائيات » مشاهدة جميع رصيد اللاعبين ومستوى النشاط
• رسائل المطور » إرسال إشعارات مباشرة لجميع المستخدمين
• ايقاف / تشغيل » ايقاف وتشغيل البوت 
—————————————
`;
    ctx.reply(admin_text);
}

module.exports = { handle };

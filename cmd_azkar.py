# ======================
# آية/دعاء عشوائي
# ======================
def get_random_azkar():
    return random.choice(AZKAR_DOA)

# ======================
# وظيفة إرسال الأذكار
# ======================
async def send_azkar_periodically(app, chat_id):
    global azkar_enabled
    while azkar_enabled:
        await app.bot.send_message(chat_id, get_random_azkar())
        await asyncio.sleep(azkar_interval)

# ======================
# التعامل مع الرسائل
# ======================
async def handle_message(update: Update, context: ContextTypes.DEFAULT_TYPE):
    global azkar_enabled, azkar_task
    text = update.message.text.strip().lower()
    chat_id = update.effective_chat.id

    if text == "اذكار":
        await context.bot.send_message(chat_id, get_random_azkar())

    elif text == "تفعيل اذكار":
        if not azkar_enabled:
            azkar_enabled = True
            await context.bot.send_message(chat_id, "✅ تم تفعيل الأذكار التلقائية كل ساعة.")
            azkar_task = asyncio.create_task(send_azkar_periodically(context.application, chat_id))
        else:
            await context.bot.send_message(chat_id, "✅ الأذكار التلقائية مفعلة بالفعل.")

    elif text == "تعطيل اذكار":
        if azkar_enabled:
            azkar_enabled = False
            if azkar_task:
                azkar_task.cancel()
                azkar_task = None
            await context.bot.send_message(chat_id, "🔴 تم تعطيل الأذكار التلقائية.")
        else:
            await context.bot.send_message(chat_id, "🔴 الأذكار التلقائية معطلة بالفعل.")

# ======================
# تشغيل البوت
# ======================
async def main():
    BOT_TOKEN = "ضع_هنا_توكن_البوت"
    app = ApplicationBuilder().token(BOT_TOKEN).build()

    app.add_handler(MessageHandler(filters.TEXT & (~filters.COMMAND), handle_message))

    print("🚀 البوت شغال وبكامل الهيبة")
    await app.run_polling()

if __name__ == "__main__":
    import asyncio
    asyncio.run(main())

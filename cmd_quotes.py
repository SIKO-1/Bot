# ======================
# الإعدادات
# ======================
quotes_enabled = False
quotes_interval = 3600  # ساعة

# ======================
# جدولة الاقتباسات
# ======================
def quotes_scheduler(bot, chat_id):
    def run():
        while True:
            if quotes_enabled:
                bot.send_message(chat_id, f"📝 اقتباس:\n\n{random.choice(QUOTES)}")
            time.sleep(quotes_interval)
    Thread(target=run, daemon=True).start()

# ======================
# الهاندلر
# ======================
def handle(bot, message):
    global quotes_enabled
    text = message.text.strip()

    if text == "اقتباس":
        bot.reply_to(message, f"📝 اقتباس:\n\n{random.choice(QUOTES)}")
        return

    if text == "تفعيل اقتباس":
        if quotes_enabled:
            bot.reply_to(message, "✅ الاقتباس مفعّل بالفعل.")
            return
        quotes_enabled = True
        quotes_scheduler(bot, message.chat.id)
        bot.reply_to(message, "🟢 تم تفعيل الاقتباسات (كل ساعة).")
        return

    if text == "تعطيل اقتباس":
        quotes_enabled = False
        bot.reply_to(message, "🔴 تم تعطيل الاقتباسات.")
        return

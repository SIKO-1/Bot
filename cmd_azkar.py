# ======================
# متغير تفعيل/تعطيل
# ======================
azkar_enabled = False  # False يعني معطل، True يعني مفعّل
azkar_interval = 3600  # 1 ساعة بالثواني

# ======================
# تفعيل / تعطيل الأذكار
# ======================
def enable_azkar():
    global azkar_enabled
    azkar_enabled = True

def disable_azkar():
    global azkar_enabled
    azkar_enabled = False

# ======================
# إرسال آية عشوائية
# ======================
def get_random_verse():
    return random.choice(QURAN_VERSES)

def send_random_verse(bot, chat_id):
    verse = get_random_verse()
    bot.send_message(chat_id, verse)

# ======================
# دالة تشغيل تلقائي كل ساعة
# ======================
def azkar_scheduler(bot, chat_id):
    def run():
        while True:
            if azkar_enabled:
                send_random_verse(bot, chat_id)
            time.sleep(azkar_interval)
    Thread(target=run, daemon=True).start()

# ======================
# تفعيل / تعطيل الأذكار
# ======================
def enable_azkar():
    global azkar_enabled
    azkar_enabled = True

def disable_azkar():
    global azkar_enabled
    azkar_enabled = False

# ======================
# إرسال آية عشوائية
# ======================
def get_random_verse():
    return random.choice(QURAN_VERSES)

def send_random_verse(bot, chat_id):
    verse = get_random_verse()
    bot.send_message(chat_id, verse)

# ======================
# تشغيل تلقائي كل ساعة
# ======================
def azkar_scheduler(bot, chat_id):
    def run():
        while True:
            if azkar_enabled:
                send_random_verse(bot, chat_id)
            time.sleep(azkar_interval)
    Thread(target=run, daemon=True).start()

# ======================
# التعامل مع الرسائل
# ======================
def handle(bot, message):
    text = message.text.strip() if message.text else ""
    chat_id = message.chat.id

    if text == "اذكار":
        send_random_verse(bot, chat_id)
    elif text == "تفعيل اذكار":
        enable_azkar()
        bot.send_message(chat_id, "✅ تم تفعيل الأذكار التلقائية كل ساعة.")
    elif text == "تعطيل اذكار":
        disable_azkar()
        bot.send_message(chat_id, "🔴 تم تعطيل الأذكار التلقائية.")

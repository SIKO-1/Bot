# ======================
# متغير تفعيل/تعطيل
# ======================
azkar_enabled = False
azkar_interval = 3600  # 1 ساعة

# ======================
# إرسال آية عشوائية
# ======================
def get_random_verse():
    return random.choice(QURAN_VERSES)

def send_random_verse(bot, chat_id):
    verse = get_random_verse()
    bot.send_message(chat_id, verse)

def azkar_scheduler(bot, chat_id):
    def run():
        while True:
            if azkar_enabled:
                send_random_verse(bot, chat_id)
            time.sleep(azkar_interval)
    Thread(target=run, daemon=True).start()

# ======================
# الدالة الأساسية handle للبوت
# ======================
def handle(bot, message):
    global azkar_enabled
    text = message.text.strip()
    chat_id = message.chat.id

    # تفعيل الأذكار التلقائية (خاص بالمطور)
    if text == "تفعيل اذكار":
        if not azkar_enabled:
            azkar_enabled = True
            bot.reply_to(message, "✅ تم تفعيل الأذكار التلقائية")
            azkar_scheduler(bot, chat_id)
        else:
            bot.reply_to(message, "⚠️ الأذكار بالفعل مفعلة")
        return

    # تعطيل الأذكار التلقائية (خاص بالمطور)
    if text == "تعطيل اذكار":
        if azkar_enabled:
            azkar_enabled = False
            bot.reply_to(message, "❌ تم تعطيل الأذكار التلقائية")
        else:
            bot.reply_to(message, "⚠️ الأذكار بالفعل معطلة")
        return

    # إرسال آية عشوائية عند كتابة "اذكار"
    if text == "اذكار":
        send_random_verse(bot, chat_id)

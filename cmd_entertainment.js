// ملف: cmd_entertainment.js
const COMMANDS = ["تسلية", "تسلّي"];

function handle(bot, msg) {
    if (!msg.text) return;
    if (!COMMANDS.includes(msg.text.trim())) return;

    const userName = msg.from.first_name || "المستخدم";

    const funText = `
╔═════════════════╗
      الأوامر الإمبراطورية - تسلية
╚═════════════════╝

مرحباً بك يا ${userName} 👑
━━━━━━━━━━━━━━━

︙أوامر التسلية كالاتي:
—————————————
⌔︙الامر ، تفعيل ، تعطيل ← { الامر }
⌔︙غنيلي ، ريمكس ، اغنيه ، شعر
⌔︙قصيده ، صوره ، متحركه ، ميوزك
⌔︙انمي ، ميمز ، ستوري
⌔︙مسلسل ، فلم
⌔︙حساب العمر( احسب + تاريخ الميلاد)
⌔︙معنى اسم + الاسم
⌔︙اقتباس ، اذكار 
⌔︙تفعيل تعطيل _ اقتباس ، الاذكار 
⌔︙وظيفته (اذكار و اقتباس رد تلقائي كل 1 ساعه)
—————————————
⌔︙تفعيل تعطيل عيد ميلاد
⌔︙اضف ، مسح عيد ميلاد
⌔︙عيد ميلاد ، قائمه الاعياد 
⌔︙مسح قائمه الاعياد
⌔︙وظيفته ( رد تلقائي تهاني عيد ميلاد مع صورة المستخدم كل 5 دقيقه)
—————————————
⌔︙زواج ~ طلاق ← {بالرد ، بالمعرف}
⌔︙جاوبه ← { بالرد ، بالمعرف }
⌔︙وظيفته :( يجاوب الشخص بصمه ميمز )
⌔︙المتزوجين ~ مسح المتزوجين
⌔︙ثنائي اليوم ، منشن
⌔︙زوجني ، عقاب ، نكات ، قصص
⌔︙اكتموه { بالرد }
—————————————
`;

    bot.sendMessage(msg.chat.id, funText);
}

module.exports = { handle };
